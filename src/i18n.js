export const LANGUAGES = { en: 'English', 'pt-BR': 'Português (Brasil)', ja: '日本語', es: 'Español' };

let current = 'en';

export function detectLanguage() {
  for (const lang of navigator.languages ?? [navigator.language]) {
    if (STRINGS[lang]) return lang;
    const base = lang.split('-')[0];
    const match = Object.keys(STRINGS).find((k) => k.split('-')[0] === base);
    if (match) return match;
  }
  return 'en';
}

export function setLanguage(lang) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  return current;
}

export function t(key, vars = {}) {
  const text = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
